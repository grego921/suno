"use client";

import React, { useState } from "react";
import { BackendConfig, ServerStats } from "../lib/types";
import { checkHealth, fetchServerStats } from "../lib/api";
import {
  Activity,
  AlertCircle,
  CheckCircle2,
  ExternalLink,
  Eye,
  EyeOff,
  Key,
  RefreshCw,
  Server,
  Wifi,
  X,
} from "lucide-react";

interface SettingsModalProps {
  isOpen: boolean;
  onClose: () => void;
  config: BackendConfig;
  onSaveConfig: (apiUrl: string, token: string) => void;
  stats?: ServerStats | null;
}

export const SettingsModal: React.FC<SettingsModalProps> = ({
  isOpen,
  onClose,
  config,
  onSaveConfig,
  stats,
}) => {
  const [apiUrl, setApiUrl] = useState(config.apiUrl);
  const [token, setToken] = useState(config.token);
  const [showToken, setShowToken] = useState(false);

  const [testing, setTesting] = useState(false);
  const [testResult, setTestResult] = useState<{
    ok?: boolean;
    latencyMs?: number;
    error?: string;
  } | null>(null);

  if (!isOpen) return null;

  const handleTest = async () => {
    setTesting(true);
    setTestResult(null);
    const res = await checkHealth(apiUrl, token);
    setTestResult(res);
    setTesting(false);
  };

  const handleSave = () => {
    onSaveConfig(apiUrl.trim(), token.trim());
    onClose();
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center bg-black/75 p-4 backdrop-blur-md animate-in fade-in duration-200">
      <div className="relative w-full max-w-lg rounded-2xl border border-cyan-500/20 bg-slate-950 p-6 shadow-2xl space-y-5">
        {/* Header */}
        <div className="flex items-center justify-between border-b border-slate-800 pb-3">
          <div className="flex items-center gap-2">
            <Server className="h-5 w-5 text-cyan-400" />
            <h3 className="text-base font-bold text-slate-100">
              ACE-Step Backend Connection
            </h3>
          </div>
          <button
            type="button"
            onClick={onClose}
            className="rounded-lg p-1 text-slate-400 hover:bg-slate-900 hover:text-white"
          >
            <X className="h-5 w-5" />
          </button>
        </div>

        {/* Notice on auto-connect */}
        <div className="rounded-xl border border-cyan-500/20 bg-cyan-950/20 p-3 text-xs text-cyan-300">
          <p className="font-semibold mb-1">💡 Quick Auto-Connection:</p>
          <p className="text-slate-400">
            When you run the notebook in Google Colab, it will print a direct link like:
          </p>
          <code className="mt-1 block rounded bg-slate-900 px-2 py-1 font-mono text-[11px] text-cyan-200 truncate">
            https://your-site.vercel.app/?api=https://...trycloudflare.com&amp;token=xyz
          </code>
        </div>

        {/* Inputs */}
        <div className="space-y-4 text-xs">
          {/* API URL */}
          <div>
            <label className="block font-semibold text-slate-300 mb-1">
              Backend Tunnel URL (Cloudflared / ngrok / local)
            </label>
            <div className="relative">
              <input
                type="text"
                value={apiUrl}
                onChange={(e) => setApiUrl(e.target.value)}
                placeholder="https://xxxx.trycloudflare.com or http://localhost:7860"
                className="w-full rounded-xl border border-slate-800 bg-slate-900 px-3 py-2 text-slate-200 placeholder-slate-600 focus:border-cyan-500/50 focus:outline-none"
              />
            </div>
          </div>

          {/* Token */}
          <div>
            <label className="block font-semibold text-slate-300 mb-1">
              API Security Token (Optional if disabled)
            </label>
            <div className="relative">
              <input
                type={showToken ? "text" : "password"}
                value={token}
                onChange={(e) => setToken(e.target.value)}
                placeholder="Paste the random token generated by Colab"
                className="w-full rounded-xl border border-slate-800 bg-slate-900 px-3 py-2 pr-10 font-mono text-slate-200 placeholder-slate-600 focus:border-cyan-500/50 focus:outline-none"
              />
              <button
                type="button"
                onClick={() => setShowToken(!showToken)}
                className="absolute right-2 top-2 text-slate-400 hover:text-white"
              >
                {showToken ? <EyeOff className="h-4 w-4" /> : <Eye className="h-4 w-4" />}
              </button>
            </div>
          </div>

          {/* Test connection feedback */}
          {testResult && (
            <div
              className={`flex items-center gap-2 rounded-xl border p-3 ${
                testResult.ok
                  ? "border-emerald-500/30 bg-emerald-950/30 text-emerald-300"
                  : "border-rose-500/30 bg-rose-950/30 text-rose-300"
              }`}
            >
              {testResult.ok ? (
                <>
                  <CheckCircle2 className="h-4 w-4 shrink-0 text-emerald-400" />
                  <div>
                    <span className="font-semibold">Connected Successfully!</span>
                    <span className="block text-[11px] text-emerald-400/80">
                      Response time: {testResult.latencyMs}ms
                    </span>
                  </div>
                </>
              ) : (
                <>
                  <AlertCircle className="h-4 w-4 shrink-0 text-rose-400" />
                  <div>
                    <span className="font-semibold">Connection Failed</span>
                    <span className="block text-[11px] text-rose-400/80">
                      {testResult.error}
                    </span>
                  </div>
                </>
              )}
            </div>
          )}

          {/* Server stats if available */}
          {stats && (
            <div className="rounded-xl border border-slate-800 bg-slate-900/40 p-3 space-y-1 text-slate-400">
              <span className="font-semibold text-slate-300">Live Server Stats:</span>
              <div className="grid grid-cols-3 gap-2 font-mono text-[11px] pt-1">
                <div>Running: <span className="text-cyan-400">{stats.jobs?.running ?? 0}</span></div>
                <div>Queued: <span className="text-purple-400">{stats.queue_size ?? 0}</span></div>
                <div>Avg Job: <span className="text-slate-200">{stats.avg_job_seconds ? `${stats.avg_job_seconds}s` : "N/A"}</span></div>
              </div>
            </div>
          )}
        </div>

        {/* Footer actions */}
        <div className="flex items-center justify-between border-t border-slate-800 pt-4">
          <button
            type="button"
            onClick={handleTest}
            disabled={testing || !apiUrl.trim()}
            className="flex items-center gap-1.5 rounded-xl border border-slate-700 bg-slate-800 px-3 py-2 text-xs font-medium text-slate-200 hover:border-cyan-500/40 hover:text-white transition-all disabled:opacity-40"
          >
            {testing ? (
              <RefreshCw className="h-3.5 w-3.5 animate-spin text-cyan-400" />
            ) : (
              <Wifi className="h-3.5 w-3.5 text-cyan-400" />
            )}
            <span>Test Connection</span>
          </button>

          <div className="flex items-center gap-2">
            <button
              type="button"
              onClick={onClose}
              className="rounded-xl px-3 py-2 text-xs font-medium text-slate-400 hover:text-white"
            >
              Cancel
            </button>
            <button
              type="button"
              onClick={handleSave}
              className="rounded-xl bg-gradient-to-r from-cyan-400 to-purple-600 px-4 py-2 text-xs font-bold text-slate-950 shadow-neon-cyan/20 hover:scale-105 active:scale-95 transition-transform"
            >
              Save Configuration
            </button>
          </div>
        </div>
      </div>
    </div>
  );
};
